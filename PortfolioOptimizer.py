def calcPerformance(adata,weights):

  means = ((weights@adata["percentChange"].values.T).mean(axis = 1)+1)**252-1
  stds = (weights@adata["percentChangePositive"].values.T).std(axis = -1) * np.sqrt(252)
  return means, stds

